a = float(input("Введите ненулевое число a: "))
b = float(input("Введите ненулевое число b: "))
if a == 0 or b == 0:
    print("Ошибка: 0 вводить нельзя")
else:
    a = abs(a)
    b = abs(b)
    print(f"Сумма модулей |a|+|b|: {a+b}")
    print(f"Разность модулей |a|-|b|: {a-b}")
    print(f"Произведение модулей |a|*|b|: {a*b}")
    print(f"Частное модулей |a|/|b|: {a/b}")