a = float(input("Введите длину катета треугольника a: "))
b = float(input("Введите длину катета треугольника b: "))
if a <= 0 or b <= 0:
    print("Ошибка: введите положиетельное число")
else:
    c = float((a ** 2 + b ** 2) ** 0.5)
    print(f"Длина гипотенузы c: {c}")
    print(f"Периметр P: {a + b + c}")