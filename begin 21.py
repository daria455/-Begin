X1 = float(input("Введите координату точки X1 вершины X1Y1: "))
Y1 = float(input("Введите координату точки Y1 вершины X1Y1: "))
X2 = float(input("Введите координату точки X2 вершины X2Y2: "))
Y2 = float(input("Введите координату точки Y2 вершины X2Y2: "))
X3 = float(input("Введите координату точки X3 вершины X3Y3: "))
Y3 = float(input("Введите координату точки Y3 вершины X3Y3: "))
A = ((X2 - X1) ** 2 + (Y2 - Y1) ** 2) ** 0.5
B = ((X3 - X2) ** 2 + (Y3 - Y2) ** 2) ** 0.5
C = ((X1 - X3) ** 2 + (Y1 - Y3) ** 2) ** 0.5
p = (A + B + C) / 2
P = A + B + C
S = (p * (p - A) * (p - B) * (p - C)) ** 0.5
print(f"Периметр: {P}")
print(f"Площадь: {S}")