Pi = 3.14
R1 = float(input("Введите длину радиуса R1: "))
R2 = float(input("Введите длину радиуса R2: "))
if R1 > R2 and R1 > 0 and R2 > 0:
    S1 = Pi * R1 ** 2
    S2 = Pi * R2 ** 2
    print(f"Площадь круга S1: { S1 }")
    print(f"Площадь круга S2: { S2 }")
    print(f"Площадь кольца S3: {S1 - S2}")
else:
    print("Ошибка: введите положительнлое число ")